// --- Open source licences -----------------------------------------------------------------------
// AboutLibraries reads the licence of every dependency out of its POM and exports them as JSON,
// which Robot › Open source licences renders (see data/LicenseRepository.kt). The reports are
// checked in under composeResources/files/licenses and regenerated by hand with `just licenses`,
// one per shipped platform, so each app lists what it actually links rather than the union.
//
// The plugin only looks at configurations named *CompileClasspath / *RuntimeClasspath, and
// Kotlin/Native has neither — what an iOS binary links is `iosArm64CompileKlibraries`. So the klibs
// are re-exposed here under a name the plugin picks up; `-PaboutLibraries.exportVariant=iosLinked`
// selects it. The attributes are copied because without them the klib variants don't resolve.
val iosArm64Klibraries = configurations.getByName("iosArm64CompileKlibraries")
configurations.register("iosLinkedRuntimeClasspath") {
    extendsFrom(iosArm64Klibraries)
    isCanBeConsumed = false
    attributes {
        iosArm64Klibraries.attributes.keySet().forEach { key ->
            @Suppress("UNCHECKED_CAST")
            attribute(key as Attribute<Any>, iosArm64Klibraries.attributes.getAttribute(key)!!)
        }
    }
}

aboutLibraries {
    collect {
        // Hand-written entries for what no Gradle dependency declares: the bundled fonts and the
        // Phosphor icons.
        configPath = file("licenses")
    }
    export {
        // Pretty-printed so a dependency bump reads as a diff of the libraries that changed.
        prettyPrint = true
        // Not shown anywhere, and about a third of the file.
        excludeFields.addAll("description", "scm", "funding", "organization")
    }
}

