package xyz.felixb.congatrol.data

import congatrol.shared.generated.resources.Res
import kotlinx.collections.immutable.ImmutableList
import kotlinx.collections.immutable.toImmutableList
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import xyz.felixb.congatrol.util.licenseReportPath

/** One open source component the app ships, with the licence(s) it is distributed under. */
data class OpenSourceLibrary(
    /** Stable across versions: `group:artifact`. */
    val id: String,
    val name: String,
    /** Null for the hand-written entries (fonts, icons), which are not versioned artifacts. */
    val version: String?,
    val author: String?,
    val website: String?,
    val licenses: ImmutableList<OpenSourceLicense>,
)

data class OpenSourceLicense(
    val name: String,
    val url: String?,
    /** The full text, or null when the report only knows the licence by name and [url]. */
    val text: String?,
)

/**
 * The open source libraries this build links, read from the licence report generated by
 * `just licenses` (see the aboutLibraries block in shared/build.gradle.kts).
 *
 * The report is a hundred kilobytes of JSON, so it is parsed once, off the main thread, and kept:
 * the list and every detail screen opened from it read the same copy.
 */
class LicenseRepository(
    private val readReport: suspend () -> String = { Res.readBytes(licenseReportPath()).decodeToString() },
) {
    private val mutex = Mutex()
    private var cached: ImmutableList<OpenSourceLibrary>? = null

    suspend fun libraries(): ImmutableList<OpenSourceLibrary> =
        mutex.withLock {
            cached ?: withContext(Dispatchers.Default) { parseLicenseReport(readReport()) }.also { cached = it }
        }
}

/**
 * Reads the report as the aboutLibraries plugin writes it: libraries naming their licences by
 * hash, and the licences once each, keyed by that hash — the Apache text is there one time, not
 * 150. The libraries come back in the order they are listed: by name, ignoring case.
 *
 * Read as a JSON tree, like everything else in the app, and lenient about what is missing: a
 * plugin upgrade that adds or drops a field changes nothing here.
 */
internal fun parseLicenseReport(json: String): ImmutableList<OpenSourceLibrary> {
    val report = Json.parseToJsonElement(json).jsonObject
    val licenses = report["licenses"] as? JsonObject
    return (report["libraries"] as? JsonArray)
        .orEmpty()
        .mapNotNull { it as? JsonObject }
        .mapNotNull { library ->
            val id = library.text("uniqueId") ?: return@mapNotNull null
            OpenSourceLibrary(
                id = id,
                name = library.text("name")?.takeIf { it.isNotBlank() } ?: id,
                version = library.text("artifactVersion")?.takeIf { it.isNotBlank() },
                author =
                    (library["developers"] as? JsonArray)
                        .orEmpty()
                        .mapNotNull { (it as? JsonObject)?.text("name")?.trim()?.takeIf(String::isNotEmpty) }
                        .distinct()
                        .joinToString(", ")
                        .ifEmpty { null },
                website = library.text("website")?.takeIf { it.isNotBlank() },
                licenses =
                    (library["licenses"] as? JsonArray)
                        .orEmpty()
                        .mapNotNull { hash -> hash.jsonPrimitive.contentOrNull?.let { licenses?.get(it) } as? JsonObject }
                        .mapNotNull { license ->
                            OpenSourceLicense(
                                name = license.text("name") ?: return@mapNotNull null,
                                url = license.text("url")?.takeIf { it.isNotBlank() },
                                text = license.text("content")?.takeIf { it.isNotBlank() }?.let(::readableLicenseText),
                            )
                        }.toImmutableList(),
            )
        }.sortedWith(compareBy({ it.name.lowercase() }, { it.id }))
        .toImmutableList()
}

/** `<<var;name=copyright;original= <year> <owner>;match=.+>>` — SPDX's markup for a replaceable span. */
private val spdxVariable = Regex("<<var;name=[^;]*;original=(.*?);match=.*?>>")
private val spdxOptional = Regex("<<(?:begin|end)Optional>>")

/** A line that opens a list item or is indented, so it must keep its own line. */
private val ownLine = Regex("""^(?:\s|[-*•]|\(?[0-9A-Za-z]{1,2}[.)]\s)""")

/** A line made of nothing but rule characters, as under the Open Font License's title. */
private val ruler = Regex("""^[-=_*]{3,}$""")

/**
 * A line at least this long was probably broken by a fixed-width wrap rather than ended on purpose.
 * Licence files wrap at 70–80 columns; their headings and closing lines are shorter.
 */
private const val WRAPPED_LINE_MIN_LENGTH = 55

/**
 * A licence text made fit for a phone-width column, without changing a word of it.
 *
 * Two things stand in the way. The SPDX texts the plugin fills in carry template markup, which is
 * reduced to the wording it wraps. And the licence files copied from upstream are hard-wrapped at
 * ~75 columns, which on a narrow screen re-wraps into alternating long and short lines — so lines
 * that were evidently wrapped are joined back into their paragraph. Headings, list items, rules and
 * blank lines stay exactly where they are.
 */
internal fun readableLicenseText(raw: String): String {
    val plain =
        raw
            .replace("\r\n", "\n")
            .replace(spdxVariable) { it.groupValues[1].trim() }
            .replace(spdxOptional, "")

    val out = StringBuilder()
    var previous = ""
    plain.trim().lines().forEachIndexed { index, rawLine ->
        val line = rawLine.trimEnd()
        val continuesParagraph =
            previous.length >= WRAPPED_LINE_MIN_LENGTH &&
                line.isNotEmpty() &&
                !ruler.matches(previous.trim()) &&
                !ruler.matches(line.trim()) &&
                !ownLine.containsMatchIn(line)
        when {
            index == 0 -> out.append(line)
            continuesParagraph -> out.append(' ').append(line)
            else -> out.append('\n').append(line)
        }
        previous = line
    }
    return out.toString()
}
